print("Витязь стоит на распутье перед камнем с надписью:")
print("«Направо пойдёшь — коня потеряешь,")
print(" налево пойдёшь — жизнь потеряешь,")
print(" прямо пойдёшь — жив будешь, да себя позабудешь».\n")

choice = input("Куда поедет витязь? (направо / налево / прямо): ").strip().lower()

if choice == "направо":
    print("\nВитязь повернул направо...")
    print("Путь привёл его в топкое болото.")
    print("Конь пал, но сам витязь остался жив.")
    print("Последствие: он потерял верного друга, но сохранил жизнь.")

elif choice == "налево":
    print("\nВитязь повернул налево...")
    print("Дорога вывела его к вражеской засаде.")
    print("В неравном бою витязь сложил голову.")
    print("Последствие: он погиб, но с честью.")

elif choice == "прямо":
    print("\nВитязь поехал прямо...")
    print("Путь был долгим и трудным, но безопасным.")
    print("Он вернулся домой живым, но забыл своё имя и подвиги.")
    print("Последствие: он жив, но потерял себя.")

elif choice == "назад" or choice == "домой":
    print("\nВитязь повернул коня обратно.")
    print("Он вернулся домой, так и не узнав, что ждало его впереди.")
    print("Последствие: он сохранил жизнь, но остался в неизвестности.")

else:
    print("\nВитязь задумался и не тронулся с места.")
    print("Камень молчит, дорога ждёт.")
    print("Последствие: выбор так и не сделан — время уходит.")